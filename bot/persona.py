def key_for(channel_id: int) -> str:
    return f"persona:{channel_id}"


def resolve(value: str | None) -> tuple[str, str] | None:
    """แปลงค่าที่เก็บในฐานข้อมูลเป็น (ชื่อที่แสดง, system prompt) — None = ใช้ค่าเริ่มต้น"""
    if not value:
        return None
    if value.startswith("custom:"):
        return "✏️ กำหนดเอง", value.removeprefix("custom:") + _COMMON
    if value in PRESETS:
        label, prompt = PRESETS[value]
        return label, prompt + _COMMON
    return None
